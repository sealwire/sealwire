#!/usr/bin/env node
// Refresh the vendored model price table.
//
//   node scripts/update-model-prices.mjs [--check]
//
// Prices are VENDORED rather than fetched at runtime, deliberately. The relay
// is local-first and works offline; a cost estimate that changed with
// connectivity would be a number nobody could reproduce, and pulling ~1.9MB
// from GitHub on every boot to decorate one column is a poor trade — as well as
// a request that announces the relay is running.
//
// Source: LiteLLM's model_prices_and_context_window.json (MIT). We keep only
// the models this relay can actually see and only the fields the estimator
// uses, which takes 1.9MB / 3213 entries down to about 9KB / 120.
//
// `--check` re-derives the file and exits non-zero if it differs, so CI can
// tell you the snapshot is stale without letting the build reach the network.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE =
  "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";

const OUT = fileURLToPath(
  new URL("../crates/relay-server/src/usage/model-prices.json", import.meta.url)
);

// Only providers we route to. Bedrock/Vertex/Azure re-list every model under
// their own keys; those are the same models at another vendor's prices, and we
// do not talk to those vendors.
const PROVIDERS = new Set(["anthropic", "openai"]);

const BASE_FIELDS = {
  input_cost_per_token: "input",
  output_cost_per_token: "output",
  cache_read_input_token_cost: "cache_read",
  cache_creation_input_token_cost: "cache_write",
};

// Anthropic prices a prompt over 200k tokens at a higher rate. For an agent
// relay that is not an edge case — long contexts are the normal shape of the
// work — so dropping this tier would under-report exactly the sessions that
// cost the most.
const TIER_FIELDS = {
  input_cost_per_token_above_200k_tokens: "input",
  output_cost_per_token_above_200k_tokens: "output",
  cache_read_input_token_cost_above_200k_tokens: "cache_read",
  cache_creation_input_token_cost_above_200k_tokens: "cache_write",
};

// An unrecognised model is newer than everything here, so it prices as the newest
// mid-tier one. Picked by rule, not by name: upstream retires names.
const FALLBACK_RULES = {
  claude: /^claude-sonnet-(\d{1,2})(?:-(\d{1,2}))?$/,
  openai: /^gpt-(\d{1,2})(?:\.(\d{1,2}))?$/,
};

export function pickFallbacks(models) {
  const picked = {};
  for (const [family, rule] of Object.entries(FALLBACK_RULES)) {
    let best = null;
    for (const key of Object.keys(models)) {
      const match = rule.exec(key);
      if (!match) continue;
      const major = Number(match[1]);
      const minor = Number(match[2] ?? 0);
      if (!best || major > best.major || (major === best.major && minor > best.minor)) {
        best = { key, major, minor };
      }
    }
    if (!best) {
      throw new Error(`no ${family} model matches ${rule}; update FALLBACK_RULES`);
    }
    picked[family] = best.key;
  }
  return picked;
}

function pick(entry, fields) {
  const out = {};
  for (const [from, to] of Object.entries(fields)) {
    const value = entry[from];
    if (typeof value === "number" && Number.isFinite(value) && value >= 0) {
      out[to] = value;
    }
  }
  return out;
}

function distil(raw) {
  const models = {};
  for (const [key, entry] of Object.entries(raw)) {
    if (!entry || typeof entry !== "object") continue;
    if (!PROVIDERS.has(entry.litellm_provider)) continue;
    // `mode` is absent on a few entries; absent means chat here.
    if (entry.mode != null && entry.mode !== "chat") continue;

    const base = pick(entry, BASE_FIELDS);
    // A rate card without both sides of the trade prices nothing.
    if (base.input == null || base.output == null) continue;

    const tier = pick(entry, TIER_FIELDS);
    models[key] = Object.keys(tier).length ? { ...base, above_200k: tier } : base;
  }
  return models;
}

// Sorted keys so a refresh that changes no prices produces no diff. An
// unordered dump would churn the file on every run and make a real price change
// impossible to spot in review.
function serialise(models, asOf) {
  const sorted = {};
  for (const key of Object.keys(models).sort()) sorted[key] = models[key];
  return `${JSON.stringify(
    {
      _comment:
        "GENERATED by scripts/update-model-prices.mjs — do not edit by hand. " +
        "Derived from LiteLLM's model_prices_and_context_window.json (MIT, Copyright (c) 2023 Berri AI). " +
        "Costs are USD per token. List prices only: no negotiated rates, no discounts, no free tier.",
      source: SOURCE,
      as_of: asOf,
      fallbacks: pickFallbacks(models),
      models: sorted,
    },
    null,
    2
  )}\n`;
}

async function main() {
  const check = process.argv.includes("--check");

  const response = await fetch(SOURCE);
  if (!response.ok) {
    console.error(`update-model-prices: ${SOURCE} returned ${response.status}`);
    process.exit(1);
  }
  const models = distil(await response.json());
  const count = Object.keys(models).length;
  if (count < 50) {
    // The upstream file is thousands of entries. Landing under fifty means the
    // shape changed and the filter silently stopped matching — writing that would
    // replace a working table with an empty one.
    console.error(`update-model-prices: only ${count} models survived the filter; refusing to write`);
    process.exit(1);
  }

  if (check) {
    // Compare prices, not the date: the stamp moves every run and would report
    // every table as stale.
    const priced = ({ fallbacks, models }) => JSON.stringify({ fallbacks, models });
    const current = priced(JSON.parse(readFileSync(OUT, "utf8")));
    if (current !== priced(JSON.parse(serialise(models, "x")))) {
      console.error("update-model-prices: vendored prices are out of date; run without --check");
      process.exit(1);
    }
    console.log(`update-model-prices: up to date (${count} models)`);
    process.exit(0);
  }

  const asOf = new Date().toISOString().slice(0, 10);
  writeFileSync(OUT, serialise(models, asOf));
  const tiered = Object.values(models).filter((m) => m.above_200k).length;
  console.log(`update-model-prices: wrote ${count} models (${tiered} with a 200k tier), as_of ${asOf}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
